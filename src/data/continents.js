/** 아시아가 잘 보이도록 지구를 동쪽으로 돌려두는 오프셋 (°) */
export const ROT_DEG = 30;

/** 경위도 → 정사(orthographic) 투영 화면 좌표 */
export function lonLatToXY(lon, lat, cx, cy, R) {
  const lonR = ((lon + ROT_DEG) * Math.PI) / 180;
  const latR = (lat * Math.PI) / 180;
  return {
    x: cx + Math.cos(latR) * Math.sin(lonR) * R,
    y: cy - Math.sin(latR) * R,
  };
}
